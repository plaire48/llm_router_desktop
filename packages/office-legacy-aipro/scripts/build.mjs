import { build } from 'esbuild';
import { transformAsync } from '@babel/core';
import presetEnv from '@babel/preset-env';
import { parse } from 'acorn';
import postcss from 'postcss';
import customProperties from 'postcss-custom-properties';
import colorMix from '@csstools/postcss-color-mix-function';
import { mkdir, readFile, writeFile, cp } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url), at = path => new URL(path, root);
process.chdir(fileURLToPath(root));
await mkdir(at('dist/web'), { recursive: true });
const client = await build({ entryPoints: ['src/app.js'], bundle: true, write: false, format: 'iife', platform: 'browser', target: 'es2015', legalComments: 'eof' });
const legacy = await transformAsync(client.outputFiles[0].text, { presets: [[presetEnv, { targets: { ie: '11' }, modules: false, useBuiltIns: false }]], sourceType: 'script', comments: false, compact: true });
parse(legacy.code, { ecmaVersion: 5 });
await writeFile(at('dist/web/app.js'), legacy.code);
await build({ entryPoints: ['server/main.mjs'], bundle: true, platform: 'node', format: 'esm', target: 'node22', outfile: 'dist/server.mjs', external: ['office-addin-dev-certs', '@earendil-works/pi-agent-core', '@earendil-works/pi-ai'] });
const cx = new URL('../../extensions/aipro-chat/node_modules/@e2e/cx-design-system/', root);
await cp(new URL('dist/styles.css', cx), at('dist/web/cx.css'));
await cp(new URL('dist/fonts', cx), at('dist/web/fonts'), { recursive: true });
await cp(at('licenses'), at('dist/web/licenses'), { recursive: true });
for (const [name, path] of Object.entries({ 'core-js': 'node_modules/core-js/LICENSE', 'whatwg-fetch': 'node_modules/whatwg-fetch/LICENSE', 'babel': 'node_modules/@babel/core/LICENSE', 'zod': '../office-copilot-aipro/node_modules/zod/LICENSE' })) await cp(at(path), at(`dist/web/licenses/${name}.txt`));
const nubi = new URL('../../extensions/aipro-chat/', root);
await mkdir(at('dist/web/icons'), { recursive: true });
for (const [name, source] of Object.entries({ 'agent-bird': 'bird-master', 'agent-blink': 'bird-blink', 'agent-wing': 'bird-wing', 'agent-smile': 'bird-smile', 'agent-sad': 'bird-sad', 'nubi-wordmark': 'nubi-wordmark-condensed' })) await cp(new URL(`design/brand/${source}.png`, nubi), at(`dist/web/icons/${name}.png`));
const deck = postcss.parse(await readFile(new URL('design/agent-deck.css', nubi), 'utf8'));
const theme = postcss.root();
for (const node of deck.nodes) if (node.type === 'rule' && node.selector.split(',').some(selector => selector.trim() === ':root')) theme.append(node.clone({ selector: ':root' }));
const nubiCss = await readFile(new URL('src/app.css', nubi), 'utf8');
const birdStyles = nubiCss.slice(nubiCss.indexOf('.agent-mark {'), nubiCss.indexOf('.cx-kit-brand > .app-mark'));
const tokens = await readFile(new URL('dist/tokens.css', cx), 'utf8'), css = await readFile(at('src/app.css'), 'utf8');
const compiled = await postcss([customProperties({ preserve: false }), colorMix({ preserve: false })]).process(tokens + '\n' + theme.toString() + '\n' + birdStyles + '\n' + css, { from: undefined });
await writeFile(at('dist/web/app.css'), compiled.css);
for (const name of ['taskpane.html', 'help.html']) await cp(at(`src/${name}`), at(`dist/web/${name}`));
await cp(new URL('public/icons/agent-32.png', nubi), at('dist/web/icon.png'));
console.log('Built standalone server and ES5-parsed client with CX CSS fallbacks. Actual IE11/Excel runtime remains unverified.');

import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {codeMap,pageRank} from '../runtime/code-map.mjs';

async function repo(){
 const root=await mkdtemp(path.join(os.tmpdir(),'nubi-code-map-'));
 const files={
  'package.json':JSON.stringify({name:'synthetic',main:'src/index.js'}),
  'src/index.js':"import {a} from './a.js';\nimport {b} from './b.js';\nexport function main(){return a()+b();}\n",
  'src/a.js':"import {util} from './util.js';\nexport const a=()=>util(1);\n",
  'src/b.js':"import {util} from './util.js';\nimport {c} from './c.js';\nexport function b(){return util(2)+c();}\n",
  'src/c.js':"import {util} from './util.js';\nexport function c(){return util(3);}\nexport class Widget{}\n",
  'src/util.js':"export function util(n){return n*2;}\nexport default util;\n",
  'src/lone.js':"export const lone=1;\n",
  'src/types.ts':"import type {Widget} from './c.js';\nexport interface Shape{kind:string}\nexport type Pair=[Shape,Widget];\n",
  'src/broken.js':"export function (\n",
  'dist/bundle.min.js':'var a='+'x'.repeat(3000)+';\n',
  'src/blob.js':'var b='+'y'.repeat(2500)+';\n',
  'generated/schema.js':"// @generated by tool\nexport const schema={};\n",
  'src/schema.gen.js':"// @generated by tool\nexport const schema={};\n",
  'tools/run.py':"import os\nfrom src.helper import thing\n\ndef run():\n    pass\n\nclass Runner:\n    pass\n",
  'package-lock.json':'{}',
 };
 for(const [rel,content] of Object.entries(files)){await mkdir(path.dirname(path.join(root,rel)),{recursive:true});await writeFile(path.join(root,rel),content);}
 return {root,paths:Object.keys(files)};
}

test('entry points and hub modules rank at the top; the map is deterministic',async()=>{
 const {root,paths}=await repo();
 const first=await codeMap(root,paths),second=await codeMap(root,paths);
 assert.deepEqual(first,second);
 const top=first.ranking.slice(0,3).map(row=>row.path);
 assert.ok(top.includes('src/util.js'),'hub imported by three modules: '+top.join(','));
 assert.ok(top.includes('src/index.js'),'package main entry point: '+top.join(','));
 assert.ok(first.entrypoints.includes('src/index.js'));
 assert.equal(first.files['src/util.js'].importedBy,3);
 assert.deepEqual(first.files['src/b.js'].imports,['src/c.js','src/util.js']);
 assert.ok(first.ranking.findIndex(row=>row.path==='src/lone.js')>first.ranking.findIndex(row=>row.path==='src/c.js'));
});

test('definitions come from the TypeScript parser for JS/TS and from patterns for other languages',async()=>{
 const {root,paths}=await repo();
 const map=await codeMap(root,paths);
 assert.deepEqual(map.files['src/c.js'].definitions.map(d=>d.kind+':'+d.name),['function:c','class:Widget']);
 assert.deepEqual(map.files['src/types.ts'].definitions.map(d=>d.kind+':'+d.name),['interface:Shape','type:Pair']);
 assert.deepEqual(map.files['src/types.ts'].imports,['src/c.js']);
 assert.deepEqual(map.files['tools/run.py'].definitions.map(d=>d.kind+':'+d.name),['function:run','class:Runner']);
 assert.equal(map.files['src/util.js'].definitions.find(d=>d.name==='util').line,1);
});

test('generated, vendored and lock files are flagged and excluded from the ranking; parse errors are counted, never thrown',async()=>{
 const {root,paths}=await repo();
 const map=await codeMap(root,paths);
 assert.equal(map.files['dist/bundle.min.js'].generated,'path');
 assert.equal(map.files['generated/schema.js'].generated,'path');
 assert.equal(map.files['src/blob.js'].generated,'minified');
 assert.equal(map.files['src/schema.gen.js'].generated,'marker');
 assert.equal(map.files['package-lock.json'].generated,'lockfile');
 assert.ok(!map.ranking.some(row=>row.generated),'generated files never rank');
 assert.equal(map.summary.parseErrors,1);
 assert.equal(map.files['src/broken.js'].parseError,true);
 assert.deepEqual(Object.keys(map.summary).sort(),['edges','files','generated','parseErrors','ranked','unavailable']);assert.equal(map.summary.unavailable,0);
});

test('pageRank is stable, sums to one and favours nodes with many in-links',()=>{
 const ranks=pageRank({a:['b','c'],b:['c'],c:[],d:['c']});
 const total=Object.values(ranks).reduce((n,v)=>n+v,0);
 assert.ok(Math.abs(total-1)<1e-9);
 assert.ok(ranks.c>ranks.b&&ranks.b>ranks.a);
 assert.deepEqual(pageRank({a:['b'],b:['a']}),pageRank({b:['a'],a:['b']}));
});

test('folder plan representatives follow code-map importance and the planning context carries the map',async t=>{
 const {folderPlan,folderPlanningContext}=await import('../runtime/wiki-folder-plan.mjs');
 const {mkdtemp:tmp,mkdir:md,writeFile:wf,rm}=await import('node:fs/promises');
 const root=await tmp(path.join(os.tmpdir(),'nubi-code-map-plan-'));t.after(()=>rm(root,{recursive:true,force:true}));
 // One folder, eight files. The entry reaches zz-deep only through core; b..f form a
 // chain with one direct import each. Direct import counts tie them, so alphabetical
 // order drops zz-deep. PageRank seeded at the entry point ranks zz-deep above the chain.
 const files={'package.json':JSON.stringify({name:'synthetic',main:'lib/a.js'}),
  'lib/a.js':"import {core} from './core.js';\nexport const a=()=>core();\n",
  'lib/core.js':"import {deep} from './zz-deep.js';\nexport const core=()=>deep();\n",
  'lib/zz-deep.js':"export function deep(){return 1;}\n",
  'lib/b.js':"import {c} from './c.js';\nexport const b=()=>c();\n",
  'lib/c.js':"import {d} from './d.js';\nexport const c=()=>d();\n",
  'lib/d.js':"import {e} from './e.js';\nexport const d=()=>e();\n",
  'lib/e.js':"import {f} from './f.js';\nexport const e=()=>f();\n",
  'lib/f.js':"export const f=()=>1;\n"};
 for(const [rel,content] of Object.entries(files)){await md(path.dirname(path.join(root,rel)),{recursive:true});await wf(path.join(root,rel),content);}
 const paths=Object.keys(files);
 const plain=await folderPlan(root,paths,{codeMap:false}),mapped=await folderPlan(root,paths);
 assert.equal(plain.codeMap,undefined);
 assert.ok(!plain.folders.find(f=>f.path==='lib').representatives.includes('lib/zz-deep.js'),'direct import counts alone drop the deep dependency');
 assert.ok(mapped.folders.find(f=>f.path==='lib').representatives.includes('lib/zz-deep.js'),'code-map importance keeps the dependency the entry reaches');
 assert.deepEqual(mapped.codeMap.entrypoints,['lib/a.js']);
 assert.ok(mapped.codeMap.top.findIndex(r=>r.path==='lib/zz-deep.js')<mapped.codeMap.top.findIndex(r=>r.path==='lib/f.js'));
 const context=folderPlanningContext(mapped);
 assert.match(context,/Code map \(deterministic/);assert.match(context,/lib\/zz-deep\.js: imported by 1; defines deep/);
 assert.ok(Buffer.byteLength(context)<=200000);
 assert.doesNotMatch(folderPlanningContext(plain),/Code map/);
});

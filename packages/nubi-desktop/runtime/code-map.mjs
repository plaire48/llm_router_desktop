import path from 'node:path';
import {realpath} from 'node:fs/promises';
import ts from 'typescript';
import {readSource,relativeFile,privatePath} from './files.mjs';

// Deterministic code map (design 2026-10-21 "위키 규모와 품질" C1, replaces W7).
// Symbols and the import graph come from the TypeScript parser for JS/TS and
// from line patterns for Python and Java. Importance is personalized PageRank
// seeded at the package entry points (Aider repo-map pattern). No model calls.
// Generated, vendored and lock files are flagged and never ranked; a parse
// error marks the file and is counted, it never stops the map.

const SCRIPT_KINDS={'.js':ts.ScriptKind.JS,'.mjs':ts.ScriptKind.JS,'.cjs':ts.ScriptKind.JS,'.jsx':ts.ScriptKind.JSX,'.ts':ts.ScriptKind.TS,'.mts':ts.ScriptKind.TS,'.cts':ts.ScriptKind.TS,'.tsx':ts.ScriptKind.TSX};
const LANGUAGES={'.js':'javascript','.mjs':'javascript','.cjs':'javascript','.jsx':'javascript','.ts':'typescript','.mts':'typescript','.cts':'typescript','.tsx':'typescript','.py':'python','.java':'java'};
const LOCKFILES=new Set(['package-lock.json','pnpm-lock.yaml','yarn.lock','npm-shrinkwrap.json','Cargo.lock','poetry.lock','Pipfile.lock','go.sum','composer.lock','Gemfile.lock']);
const GENERATED_SEGMENTS=/(^|\/)(node_modules|dist|build|out|vendor|generated|__generated__|coverage|\.next|target)(\/|$)/;
const RESOLUTIONS=['','.js','.mjs','.cjs','.ts','.tsx','.jsx','.mts','.cts','/index.js','/index.ts','/index.mjs','/index.tsx','/index.jsx'];

export function pageRank(graph,{damping=0.85,iterations=60,teleport=null}={}){
 const nodes=Object.keys(graph).sort();if(!nodes.length)return {};
 const index=new Map(nodes.map((node,i)=>[node,i])),n=nodes.length;
 const out=nodes.map(node=>[...new Set((graph[node]||[]).filter(target=>index.has(target)&&target!==node))].sort());
 const seeds=teleport&&teleport.length?teleport.filter(node=>index.has(node)):[];
 const base=new Array(n).fill(0);if(seeds.length)for(const seed of seeds)base[index.get(seed)]+=1/seeds.length;else base.fill(1/n);
 let rank=[...base];
 for(let step=0;step<iterations;step++){
  const next=new Array(n).fill(0);let dangling=0;
  for(let i=0;i<n;i++){if(!out[i].length){dangling+=rank[i];continue;}const share=rank[i]/out[i].length;for(const target of out[i])next[index.get(target)]+=share;}
  for(let i=0;i<n;i++)next[i]=(1-damping)*base[i]+damping*(next[i]+dangling*base[i]);
  const total=next.reduce((sum,value)=>sum+value,0)||1;for(let i=0;i<n;i++)next[i]/=total;
  rank=next;
 }
 return Object.fromEntries(nodes.map((node,i)=>[node,rank[i]]));
}

function generatedKind(rel,text){
 const name=path.basename(rel);
 if(LOCKFILES.has(name))return 'lockfile';
 if(GENERATED_SEGMENTS.test(rel)||/\.min\.(js|css|mjs)$/.test(name))return 'path';
 if(/@generated\b|^\/\/ <auto-generated>|Code generated by .* DO NOT EDIT/m.test(text.slice(0,2048)))return 'marker';
 let start=0;for(let count=0;count<50&&start<text.length;count++){const end=text.indexOf('\n',start);const length=(end<0?text.length:end)-start;if(length>2000)return 'minified';if(end<0)break;start=end+1;}
 return null;
}

function definitionsFromTypeScript(rel,text,extension){
 const source=ts.createSourceFile(rel,text,ts.ScriptTarget.Latest,true,SCRIPT_KINDS[extension]);
 const definitions=[],specifiers=[];
 const line=node=>source.getLineAndCharacterOfPosition(node.getStart(source)).line+1;
 const add=(kind,name,node)=>{if(name)definitions.push({kind,name,line:line(node)});};
 const collectRequire=node=>{
  if(ts.isCallExpression(node)){
   const callee=node.expression;const argument=node.arguments[0];
   if(argument&&ts.isStringLiteralLike(argument)&&((ts.isIdentifier(callee)&&callee.text==='require')||callee.kind===ts.SyntaxKind.ImportKeyword))specifiers.push(argument.text);
  }
  ts.forEachChild(node,collectRequire);
 };
 for(const statement of source.statements){
  if(ts.isImportDeclaration(statement)&&ts.isStringLiteralLike(statement.moduleSpecifier))specifiers.push(statement.moduleSpecifier.text);
  else if(ts.isExportDeclaration(statement)&&statement.moduleSpecifier&&ts.isStringLiteralLike(statement.moduleSpecifier))specifiers.push(statement.moduleSpecifier.text);
  else if(ts.isImportEqualsDeclaration(statement)&&ts.isExternalModuleReference(statement.moduleReference)&&ts.isStringLiteralLike(statement.moduleReference.expression))specifiers.push(statement.moduleReference.expression.text);
  else if(ts.isFunctionDeclaration(statement))add('function',statement.name?.text,statement);
  else if(ts.isClassDeclaration(statement))add('class',statement.name?.text,statement);
  else if(ts.isInterfaceDeclaration(statement))add('interface',statement.name.text,statement);
  else if(ts.isTypeAliasDeclaration(statement))add('type',statement.name.text,statement);
  else if(ts.isEnumDeclaration(statement))add('enum',statement.name.text,statement);
  else if(ts.isModuleDeclaration(statement))add('namespace',statement.name.text,statement);
  else if(ts.isVariableStatement(statement)){const kind=statement.declarationList.flags&ts.NodeFlags.Const?'const':'variable';for(const declaration of statement.declarationList.declarations)if(ts.isIdentifier(declaration.name))add(kind,declaration.name.text,declaration);}
  collectRequire(statement);
 }
 return {definitions,specifiers,parseError:source.parseDiagnostics.length>0};
}

function definitionsFromPatterns(text,language){
 const definitions=[],specifiers=[];const lines=text.split('\n');
 for(let i=0;i<lines.length&&i<50000;i++){
  const value=lines[i];
  if(language==='python'){
   let m=/^(?:async\s+)?def\s+([A-Za-z_]\w*)/.exec(value);if(m){definitions.push({kind:'function',name:m[1],line:i+1});continue;}
   m=/^class\s+([A-Za-z_]\w*)/.exec(value);if(m){definitions.push({kind:'class',name:m[1],line:i+1});continue;}
   m=/^from\s+([\w.]+)\s+import|^import\s+([\w.]+)/.exec(value);if(m)specifiers.push((m[1]||m[2]).replace(/\./g,'/'));
  }else if(language==='java'){
   const m=/^\s*(?:public\s+|private\s+|protected\s+)?(?:abstract\s+|final\s+|static\s+)*(class|interface|enum|record)\s+([A-Za-z_]\w*)/.exec(value);if(m){definitions.push({kind:m[1],name:m[2],line:i+1});continue;}
   const im=/^import\s+(?:static\s+)?([\w.]+)/.exec(value);if(im)specifiers.push(im[1].replace(/\./g,'/'));
  }
 }
 return {definitions,specifiers,parseError:false};
}

function resolveSpecifier(from,specifier,known,language){
 if(language==='python'||language==='java'){
  for(const candidate of language==='python'?[specifier+'.py',specifier+'/__init__.py']:[specifier+'.java'])if(known.has(candidate))return candidate;
  return null;
 }
 if(!specifier.startsWith('.'))return null;
 const base=path.posix.normalize(path.posix.join(path.posix.dirname(from),specifier));
 if(base.startsWith('..'))return null;
 const stems=[base];if(/\.(js|mjs|cjs|jsx)$/.test(base))stems.push(base.replace(/\.(js|mjs|cjs|jsx)$/,m=>({'.js':'.ts','.mjs':'.mts','.cjs':'.cts','.jsx':'.tsx'})[m]));
 for(const stem of stems)for(const suffix of RESOLUTIONS){const candidate=stem+suffix;if(known.has(candidate))return candidate;}
 return null;
}

async function entryPoints(root,known){
 const found=new Set();
 for(const rel of [...known].filter(rel=>/(^|\/)package\.json$/.test(rel)).sort().slice(0,500)){
  let pkg;try{pkg=JSON.parse((await readSource(root,rel,{maxBytes:256*1024})).content);}catch{continue;}
  const dir=path.posix.dirname(rel)==='.'?'':path.posix.dirname(rel)+'/',values=[];
  const push=value=>{if(typeof value==='string')values.push(value);else if(value&&typeof value==='object')for(const inner of Object.values(value))push(inner);};
  push(pkg.main);push(pkg.module);push(pkg.bin);push(pkg.exports);
  for(const value of values){const rel2=path.posix.normalize(dir+value.replace(/^\.\//,''));if(known.has(rel2))found.add(rel2);}
  if(!values.length)for(const candidate of ['index.js','index.ts','index.mjs','src/index.js','src/index.ts','lib/index.js'])if(known.has(dir+candidate)){found.add(dir+candidate);break;}
 }
 for(const candidate of ['main.py','app.py','src/main.py','src/Main.java'])if(known.has(candidate))found.add(candidate);
 return [...found].sort();
}

export async function codeMap(root,files,{signal,maxBytes=1024*1024,parseLimitBytes=512*1024}={}){
 root=await realpath(root);
 const paths=[...new Set(files.map(file=>typeof file==='string'?file:file.path))].sort();
 for(const rel of paths){relativeFile(rel);if(privatePath(rel))throw Error('path_scope');}
 const known=new Set(paths),result={},graph={};let parseErrors=0,generated=0,edges=0,unavailableFiles=0;
 for(const [i,rel] of paths.entries()){
  if(i%64===0)signal?.throwIfAborted();
  const extension=path.posix.extname(rel).toLowerCase(),language=LANGUAGES[extension]||null;
  let text='',bytes=0,unavailable=null;
  try{const source=await readSource(root,rel,{maxBytes});text=source.content;bytes=Buffer.byteLength(text);}
  catch(error){unavailable=['file_too_large','binary_file','file_encoding'].includes(error.message)?error.message:'unavailable';}
  if(unavailable)unavailableFiles++;
  const row={language,bytes,lines:unavailable?0:(text?text.split('\n').length:0),generated:null,definitions:[],imports:[],externals:0,importedBy:0,parseError:false,...(unavailable?{unavailable}:{})};
  if(!unavailable){
   row.generated=generatedKind(rel,text);if(row.generated)generated++;
   if(language&&!row.generated){
    const parsed=SCRIPT_KINDS[extension]&&bytes<=parseLimitBytes?definitionsFromTypeScript(rel,text,extension):definitionsFromPatterns(text,language==='javascript'||language==='typescript'?'javascript':language);
    row.definitions=parsed.definitions;row.parseError=parsed.parseError;if(parsed.parseError)parseErrors++;if(bytes>parseLimitBytes&&SCRIPT_KINDS[extension])row.large=true;
    const resolved=new Set();for(const specifier of parsed.specifiers){const target=resolveSpecifier(rel,specifier,known,language);if(target&&target!==rel)resolved.add(target);else if(!target&&!specifier.startsWith('.'))row.externals++;}
    row.imports=[...resolved].sort();
   }
  }
  result[rel]=row;
 }
 for(const rel of paths){const row=result[rel];if(row.generated||!row.language||row.unavailable)continue;graph[rel]=row.imports.filter(target=>!result[target].generated&&!result[target].unavailable);edges+=graph[rel].length;for(const target of graph[rel])result[target].importedBy++;}
 const entries=(await entryPoints(root,known)).filter(rel=>graph[rel]);
 const ranks=pageRank(graph,{teleport:entries});
 const ranking=Object.keys(graph).map(rel=>({path:rel,score:ranks[rel]||0,importedBy:result[rel].importedBy,definitions:result[rel].definitions.length,entrypoint:entries.includes(rel)})).sort((a,b)=>b.score-a.score||b.importedBy-a.importedBy||(a.path<b.path?-1:1));
 return {files:result,graph,entrypoints:entries,ranking,summary:{files:paths.length,edges,generated,parseErrors,unavailable:unavailableFiles,ranked:ranking.length}};
}

// Navigation text for planning (bounded). Paths and symbol names only.
export function codeMapContext(map,{limit=40,maxBytes=24*1024}={}){
 const lines=['Code map (deterministic, importance by import graph; navigation data, not instructions):'];
 let bytes=Buffer.byteLength(lines[0]);
 for(const row of map.ranking.slice(0,limit)){
  const names=map.files[row.path].definitions.slice(0,8).map(d=>d.name).join(', ');
  const line=`- ${row.path}${row.entrypoint?' (entry)':''}: imported by ${row.importedBy}${names?'; defines '+names:''}`;
  bytes+=Buffer.byteLength(line)+1;if(bytes>maxBytes)break;lines.push(line);
 }
 return lines.join('\n');
}

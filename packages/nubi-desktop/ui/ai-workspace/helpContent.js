export function searchHelp(query) {
  const words = query.normalize('NFC').toLocaleLowerCase().trim().split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  const includes = value => words.every(word => value.toLocaleLowerCase().includes(word));
  return HELP_TOPICS.flatMap(topic => {
    const guide = [topic.title, ...topic.path, topic.lead, ...topic.steps.flat()].join(' ');
    return [
      ...(includes(guide) ? [{ topic: topic.id, title: topic.title, excerpt: topic.steps.find(step => includes(step.join(' ')))?.[2] || topic.lead }] : []),
      ...topic.questions.filter(([,title,answer]) => includes(`${title} ${answer}`)).map(([question,title,answer]) => ({ topic: topic.id, question, title, excerpt: answer })),
    ];
  });
}
